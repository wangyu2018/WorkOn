/** 场景最小间隔（ms） */
export const SCENE_MIN_INTERVAL: Record<ChatterScene, number> = {
  general: 30 * 60_000,
  focus: 30 * 60_000,
  slack: 15 * 60_000,
  meeting: 60 * 60_000,
  overworked: 30 * 60_000,
  lunch: 20 * 60_000, // 一天一次（检测侧控制）
  standup: 60 * 60_000,
  offwork: 20 * 60_000, // 一天一次
  lateNight: 60 * 60_000
}

export function pickChatter(scene: ChatterScene, recent: string[]): string {
  const pool = CHATTER_POOLS[scene]
  const fresh = pool.filter((l) => !recent.includes(l))
  const from = fresh.length > 0 ? fresh : pool
  return from[Math.floor(Math.random() * from.length)]
}
